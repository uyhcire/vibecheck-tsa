"""Generate the per-cell kernel checks (Ci/proof/SafeCells{0..5}.lean) and the combining SafeCells.lean."""
N = 267; G = 8
per = (N + G - 1) // G
defs = '''import Ci.proof.SafeProof

/-! The per-cell interval check (`cellOk`); the kernel evaluates it in `Ci/proof/SafeCells*.lean`, one theorem per
cell so that each kernel call stays small. -/

namespace Ci.Proof.SafeIv
open Vibecheck Jsb Ci.Lawfirst

/-- Bisection weights: every coordinate but x, h and the stall bit, normalised by the box's own widths, sin θ (dz)
ten times as heavy (it drives the α margin, the binding check near the level-off altitude). -/
def dimsOf (B : CLOf Iv) : List (Nat × Int) :=
  (List.range 20).filterMap fun i =>
    if i == 0 || i == 1 || i == 11 then none else
    let w := width (B.get i)
    if w ≤ 0 then none else some (i, (if i == 3 || i == 5 then 10 else 1) * 1000000000000 / w)

def cellOk (i : Nat) : Bool := checkRec ok [] (dimsOf (cellBox i)) 22 (cellBox i)

end Ci.Proof.SafeIv
'''
open("../SafeCellDefs.lean", "w").write(defs)
for g in range(G):
    lines = ["import Ci.proof.SafeCellDefs", "", f"/-! Kernel evaluation of `cellOk` on cells {g*per}..{min(N, (g+1)*per)-1} (generated by `Ci/proof/py/gencells.py`). -/", "",
             "namespace Ci.Proof.SafeIv", ""]
    for k in range(g * per, min(N, (g + 1) * per)):
        lines.append("-- kernel evaluation of one to a few dozen interval ticks")
        lines.append("set_option maxHeartbeats 40000000 in")
        lines.append(f"theorem cell_{k} : cellOk {k} = true := by decide +kernel")
    lines += ["", "end Ci.Proof.SafeIv", ""]
    open(f"../SafeCells{g}.lean", "w").write("\n".join(lines))
imports = "\n".join(f"import Ci.proof.SafeCells{g}" for g in range(G))
def tree(lo, hi, ind):
    # proof of cellOk i = true given lo ≤ i < hi (hypotheses hl, hh)
    if hi - lo == 1:
        return [f"{ind}obtain rfl : i = {lo} := by omega", f"{ind}exact cell_{lo}"]
    m = (lo + hi) // 2
    out = [f"{ind}rcases Nat.lt_or_ge i {m} with hh | hl"]
    out += [f"{ind}· " + l.lstrip() if j == 0 else f"{ind}  " + l[len(ind):] for j, l in enumerate(tree(lo, m, ind))]
    out += [f"{ind}· " + l.lstrip() if j == 0 else f"{ind}  " + l[len(ind):] for j, l in enumerate(tree(m, hi, ind))]
    return out
cases = "\n".join(tree(0, N, "  "))
main = f'''{imports}

/-! The one-tick safety and climb theorem for the terminal set of `Ci.Proof.lawT`, from the kernel-checked cells
(generated by `Ci/proof/py/gencells.py`). -/

namespace Ci.Proof.SafeIv
open Vibecheck Jsb Ci.Lawfirst

set_option maxRecDepth 100000

theorem boxTab_size : TData.boxTab.size = {N} := by decide

theorem cells_ok (i : Nat) (hh : i < {N}) : cellOk i = true := by
  have hl : 0 ≤ i := Nat.zero_le i
{cases}

theorem cell_sound (i : Nat) (hi : i < TData.boxTab.size) (c : CLOf Fx) (hc : (cellBox i).Mem c) : Pt c :=
  checkRec_sound ok Pt [] _ ok_sound 22 (cellBox i) (cells_ok i (boxTab_size ▸ hi)) c hc (by simp)

/-- One-tick safety and climb of the terminal set: from every state in T the tick passes `safeOk` at all 8
substeps and climbs (vz ≥ 2 m/s and h rising, or h ≥ 2500 m) at all 8. -/
theorem tick_safe_climb (s : State) (m : Mem) (hT : lawT.inT (s, m) = true) :
    (Ci.tickT lawT s m).safe = true ∧ (Ci.tickT lawT s m).climb = true := by
  have hb : boxOk (s, m) = true := by
    have : inT (s, m) = true := hT
    unfold inT at this; simp only [Bool.and_eq_true] at this; exact this.2
  unfold boxOk at hb
  simp only [Bool.and_eq_true, decide_eq_true_eq] at hb
  obtain ⟨⟨hi, hac⟩, hm⟩ := hb
  have := cell_sound _ hi (pt (s, m)) hm m rfl hac
  exact ⟨this.1, this.2.1⟩

/-- The tick's end state stays in T's altitude band. -/
theorem tick_band_h (s : State) (m : Mem) (hT : lawT.inT (s, m) = true) :
    hLoT ≤ (Ci.tickT lawT s m).s.h.raw ∧ (Ci.tickT lawT s m).s.h.raw < hHiT := by
  have hb : boxOk (s, m) = true := by
    have : inT (s, m) = true := hT
    unfold inT at this; simp only [Bool.and_eq_true] at this; exact this.2
  unfold boxOk at hb
  simp only [Bool.and_eq_true, decide_eq_true_eq] at hb
  obtain ⟨⟨hi, hac⟩, hm⟩ := hb
  have h := (cell_sound _ hi ⟨s, ⟨m.eI⟩⟩ hm m rfl hac).2.2
  dsimp only at h
  exact h

end Ci.Proof.SafeIv
'''
open("../SafeCells.lean", "w").write(main)
print("ok")
