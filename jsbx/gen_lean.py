"""usage: gen_lean.py CFG.json C172P.xml OUT.lean  (constants: harness dump bits; aero functions: XML)."""
import json, re, sys
import xml.etree.ElementTree as ET

PROPS = {
    'aero/qbar-psf': 'qbar', 'metrics/Sw-sqft': 'Sw', 'metrics/bw-ft': 'bw', 'metrics/cbarw-ft': 'cbar',
    'aero/alpha-rad': 'alpha', 'aero/beta-rad': 'beta', 'aero/mag-beta-rad': 'magBeta',
    'fcs/flap-pos-deg': 'flapDeg', 'fcs/mag-elevator-pos-rad': 'magElev', 'fcs/elevator-pos-rad': 'elev',
    'fcs/left-aileron-pos-rad': 'ailL', 'fcs/rudder-pos-rad': 'rud', 'aero/bi2vel': 'bi2vel',
    'aero/ci2vel': 'ci2vel', 'velocities/p-aero-rad_sec': 'pAero', 'velocities/q-aero-rad_sec': 'qAero',
    'velocities/r-aero-rad_sec': 'rAero', 'aero/stall-hyst-norm': 'stall', 'aero/alphadot-rad_sec': 'adot',
    'aero/h_b-mac-ft': 'hbMac', 'velocities/u-aero-fps': 'uAero',
    'propulsion/engine/prop-induced-velocity_fps': 'vind', 'atmosphere/rho-slugs_ft3': 'rho',
}
AXES = ['DRAG', 'SIDE', 'LIFT', 'ROLL', 'PITCH', 'YAW']


def ident(s):
    return re.sub(r'[^A-Za-z0-9_]', '_', s)


def lit(t):
    r = repr(float(t))
    return f'({r})' if r.startswith('-') else r


def bits(h):
    return f'Float.ofBits {h}'


class Gen:
    def __init__(self):
        self.tables = []
        self.ntab = 0

    def table(self, el, hint):
        ivs = el.findall('independentVar')
        nums = el.find('tableData').text.split()
        name = f'tab_{ident(hint)}_{self.ntab}'
        self.ntab += 1
        if len(ivs) == 1:
            rows = len(nums) // 2
            self.tables.append((name, rows, 1, ['0.0', '0.0'] + nums))
            return f'({name}.get1 {self.prop(ivs[0].text.strip())})'
        lines = [l.split() for l in el.find('tableData').text.strip().splitlines() if l.strip()]
        cols = len(lines[0])
        data = ['0.0'] + lines[0]
        for l in lines[1:]:
            assert len(l) == cols + 1
            data += l
        rk = [v for v in ivs if v.get('lookup') == 'row'][0].text.strip()
        ck = [v for v in ivs if v.get('lookup') == 'column'][0].text.strip()
        self.tables.append((name, len(lines) - 1, cols, data))
        return f'({name}.get2 {self.prop(rk)} {self.prop(ck)})'

    def prop(self, p):
        if p.startswith('aero/function/'):
            return 'f_' + ident(p.split('/')[-1])
        return 'i.' + PROPS[p]

    def expr(self, el, hint):
        if el.tag == 'table':
            return self.table(el, hint)
        terms = []
        for c in el:
            if c.tag == 'property':
                terms.append(self.prop(c.text.strip()))
            elif c.tag == 'value':
                terms.append(f'(S.lit {lit(c.text)})')
            elif c.tag == 'table':
                terms.append(self.table(c, hint))
            else:
                terms.append(self.expr(c, hint))
        if el.tag == 'product':
            return '(' + ' * '.join(['S.one'] + terms) + ')'
        if el.tag == 'sum':
            return '(' + ' + '.join(['S.zero'] + terms) + ')'
        raise ValueError(el.tag)


def main():
    cfg = json.load(open(sys.argv[1]))
    root = ET.parse(sys.argv[2]).getroot()
    out = []
    w = out.append
    w('import JsbExact.Table')
    w('')
    w('/-! Generated by `jsbx/gen_lean.py` from `c172p.xml` and a harness config dump. Do not edit. -/')
    w('')
    w('namespace JsbExact.Gen')
    w('open JsbExact S')
    w('')
    for k, v in cfg.items():
        if isinstance(v, str):
            w(f'def {ident(k)} : Float := {bits(v)}')
        elif isinstance(v, list):
            w(f'def {ident(k)} : Array Float := #[{", ".join(bits(x) for x in v)}]')
        elif isinstance(v, dict):
            w(f'def tab_{ident(k)} : Table := ⟨{v["rows"]}, {v["cols"]}, #[{", ".join(bits(x) for x in v["data"])}]⟩')
    gears = sorted((k for k in cfg if re.fullmatch(r'gear\d+', k)), key=lambda k: int(k[4:]))
    w(f'def gears : Array (Array Float) := #[{", ".join(gears)}]')
    w('')
    for comp in root.find('flight_control').iter():
        out_el = comp.find('output')
        if comp.tag == 'aerosurface_scale' and out_el is not None:
            n = ident(out_el.text.strip())
            dom, rng = comp.find('domain'), comp.find('range')
            vals = {'inMin': dom.find('min').text if dom is not None else '-1', 'inMax': dom.find('max').text if dom is not None else '1',
                    'outMin': rng.find('min').text, 'outMax': rng.find('max').text,
                    'gain': comp.find('gain').text if comp.find('gain') is not None else '1'}
            for k, v in vals.items():
                w(f'def fcs_{n}_{k} : Float := {lit(v)}')
        if comp.tag == 'summer' and comp.find('clipto') is not None:
            n = ident(comp.get('name'))
            w(f'def fcs_{n}_min : Float := {lit(comp.find("clipto/min").text)}')
            w(f'def fcs_{n}_max : Float := {lit(comp.find("clipto/max").text)}')
    w('')
    g = Gen()
    aero = root.find('aerodynamics')
    lets, axes = [], {a: [] for a in AXES}
    for f in aero.findall('function'):
        n = ident(f.get('name').split('/')[-1])
        body = [c for c in f if c.tag != 'description'][0]
        lets.append((f'f_{n}', g.expr(body, n)))
    for ax in aero.findall('axis'):
        for f in ax.findall('function'):
            n = ident(f.get('name').split('/')[-1])
            body = [c for c in f if c.tag != 'description'][0]
            lets.append((f'c_{n}', g.expr(body, n)))
            axes[ax.get('name')].append(f'c_{n}')
    for name, rows, cols, data in g.tables:
        w(f'def {name} : Table := ⟨{rows}, {cols}, #[{", ".join(lit(x) for x in data)}]⟩')
    w('')
    w('variable {α : Type} [Scalar α]')
    w('')
    w('/-- Properties the c172p aerodynamic functions read. -/')
    w('structure AeroIn (α : Type) where')
    for p in sorted(set(PROPS.values())):
        w(f'  {p} : α')
    w('')
    w('/-- Axis sums in document order (DRAG, SIDE, LIFT in wind axes; ROLL, PITCH, YAW in body axes). -/')
    w('structure AeroOut (α : Type) where')
    for a in AXES:
        w(f'  {a.lower()} : α')
    w('')
    w('def aero (i : AeroIn α) : AeroOut α :=')
    for n, e in lets:
        w(f'  let {n} := {e}')
    w('  { ' + ', '.join(f'{a.lower()} := ' + ' + '.join(['S.zero'] + axes[a]) for a in AXES) + ' }')
    w('')
    w('end JsbExact.Gen')
    open(sys.argv[3], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
