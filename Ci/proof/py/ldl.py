"""Exact LDL^T certificates for the node matrices of TData.pTab, as a Lean file proving them positive definite."""
import re
from fractions import Fraction as Fr
src = open("../TData.lean").read()
mats = []
n = 0
while True:
    m = re.search(rf"^def p{n} : Array \(Array Int\) := (#\[.*\])$", src, re.M)
    if not m: break
    rows = re.findall(r"#\[([-\d, ]+)\]", m.group(1))
    mats.append([[int(v) for v in r.split(",")] for r in rows]); n += 1
def ldl(M):
    A = [[Fr(v) for v in r] for r in M]
    L = [[Fr(0)] * 7 for _ in range(7)]; D = [Fr(0)] * 7
    for i in range(7):
        for j in range(i + 1):
            s = A[i][j] - sum(L[i][k] * L[j][k] * D[k] for k in range(j))
            if i == j: D[i] = s; L[i][i] = Fr(1)
            else: L[i][j] = s / D[j]
    return L, D
def q(x): return f"({x.numerator}/{x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"
out = ["import Proofs.CiProof.Skeleton", "", "/-! Generated by `Ci/proof/py/ldl.py`: each node matrix of `TData.pTab` is positive semidefinite, by an exact",
       "LDLᵀ decomposition: `xᵀ P x = Σ_k D_k (Σ_i L_ik x_i)²` with every `D_k > 0`; hence the interpolated form `P` is",
       "positive semidefinite at every state (`P_psd`), discharging the `hPsd` hypothesis of `tickInT_of_obligations`. -/", "",
       "namespace Proofs.CiProof.Skel", "open Matrix", ""]
for n, M in enumerate(mats):
    L, D = ldl(M)
    xs = [f"x {i}" for i in range(7)]
    lhs = " + ".join(f"({M[i][j]} : ℝ) * x {i} * x {j}" for i in range(7) for j in range(7))
    terms = []
    for k in range(7):
        lin = " + ".join(f"{q(L[i][k])} * x {i}" for i in range(k, 7))
        terms.append(f"{q(D[k])} * ({lin}) ^ 2")
    out.append(f"theorem node{n}_form (x : Fin 7 → ℝ) : {lhs} = {' + '.join(terms)} := by ring")
    out.append(f"theorem node{n}_nonneg (x : Fin 7 → ℝ) : 0 ≤ {lhs} := by rw [node{n}_form]; positivity")
    mat = "!![" + "; ".join(", ".join(f"(({v} : ℤ) : ℝ)" for v in r) for r in M) + "]"
    out.append(f"theorem pNode{n}_eq : pNode {n} = {mat} := by")
    out.append("  ext a b; fin_cases a <;> fin_cases b <;> rfl")
    out.append(f"theorem pNode{n}_symm : (pNode {n})ᵀ = pNode {n} := by")
    out.append(f"  rw [pNode{n}_eq]; ext a b; fin_cases a <;> fin_cases b <;> rfl")
    out.append(f"theorem pNode{n}_psd : (pNode {n}).PosSemidef := by")
    out.append(f"  refine Matrix.posSemidef_iff_dotProduct_mulVec.mpr ⟨pNode{n}_symm, fun x => ?_⟩")
    out.append(f"  rw [star_trivial, pNode{n}_eq]")
    out.append("  simp only [dotProduct, mulVec, Fin.sum_univ_seven, of_apply, cons_val', cons_val_zero, cons_val_one,")
    out.append("    empty_val', cons_val_fin_one, Matrix.cons_val, Fin.isValue]")
    out.append("  push_cast")
    out.append(f"  have := node{n}_nonneg x")
    out.append("  linarith")
    out.append("")
nn = len(mats)
out.append(f"theorem pTab_size : Ci.Proof.TData.pTab.size = {nn} := by decide")
out.append("")
out.append(f"theorem pNode_zero (j : Nat) (hj : {nn} ≤ j) : pNode j = 0 := by")
out.append("  ext a b")
out.append("  simp only [pNode, Matrix.zero_apply]")
out.append("  have hn : Ci.Proof.TData.pTab[j]? = none := getElem?_neg _ _ (by rw [pTab_size]; omega)")
out.append("  simp [getElem!_def, hn, show (default : Array Int) = #[] from rfl, show (default : Array (Array Int)) = #[] from rfl]")
out.append("")
out.append("theorem pNode_psd (j : Nat) : (pNode j).PosSemidef ∧ (pNode j)ᵀ = pNode j := by")
out.append(f"  by_cases hj : j < {nn}")
out.append("  · interval_cases j")
for n in range(nn):
    out.append(f"    · exact ⟨pNode{n}_psd, pNode{n}_symm⟩")
out.append("  · rw [pNode_zero j (by omega)]; exact ⟨PosSemidef.zero, by simp⟩")
out.append("")
out.append("""theorem P_psd (p : Jsb.State × Ci.Lawfirst.Mem) : (P p).PosSemidef ∧ (P p)ᵀ = P p := by
  have w0 : 0 ≤ wt p.1.h.raw := le_max_left _ _
  have w1 : wt p.1.h.raw ≤ 1 := max_le (by norm_num) (min_le_left _ _)
  obtain ⟨a0, s0⟩ := pNode_psd (Ci.Proof.nodeJ p.1.h.raw)
  obtain ⟨a1, s1⟩ := pNode_psd (Ci.Proof.nodeJ p.1.h.raw + 1)
  have hk : (0 : ℝ) ≤ ((2 : ℝ) ^ Ci.Proof.TData.pK)⁻¹ := by positivity
  refine ⟨?_, ?_⟩
  · unfold P
    exact ((a0.smul (by linarith)).add (a1.smul w0)).smul hk
  · unfold P
    rw [transpose_smul, transpose_add, transpose_smul, transpose_smul, s0, s1]""")
out.append("")
out.append("""/-- `TInvariant lawT` from the remaining obligations, with the positive semidefiniteness discharged. -/
theorem tInvariant_of_obligations'
    (hin : ∀ p, L.inT p = true → side p ∧ qf (P p) (z p) ≤ rIn p ^ 2)
    (hout : ∀ p, side p → qf (P p) (z p) ≤ rOut p ^ 2 → L.inT p = true)
    (hside : ∀ s m, L.inT (s, m) = true → side ((Ci.tickT L s m).s, (Ci.tickT L s m).m))
    (henc : ∀ s m, L.inT (s, m) = true → ∃ (A : Matrix (Fin 7) (Fin 7) ℝ) (e : Fin 7 → ℝ) (ρ ε : ℝ),
      z ((Ci.tickT L s m).s, (Ci.tickT L s m).m) = A *ᵥ z (s, m) + e ∧
      (ρ ^ 2 • P (s, m) - Aᵀ * P ((Ci.tickT L s m).s, (Ci.tickT L s m).m) * A).PosSemidef ∧
      0 ≤ ρ ∧ 0 ≤ ε ∧ qf (P ((Ci.tickT L s m).s, (Ci.tickT L s m).m)) e ≤ ε ^ 2 ∧
      ρ * rIn (s, m) + ε ≤ rOut ((Ci.tickT L s m).s, (Ci.tickT L s m).m)) :
    Ci.Goals.TInvariant L :=
  tInvariant_of_obligations P_psd hin hout hside henc""")
out.append("")
out.append("end Proofs.CiProof.Skel")
open("../../../proofs/Proofs/CiProof/NodePsd.lean", "w").write("\n".join(out) + "\n")
print(len(mats), "nodes")
