"""Generate proofs/Proofs/CiProof/StaticCert.lean: for each 100 m node interval i, slow coordinate k and node
j ∈ {i, i+1}:  Rb_i · x_k² ≤ slowB[i][k]² · xᵀ P_j x  (Rb_i = max(r2_i, r2_{i+1}) + 1), by an exact LDLᵀ certificate
of slowB² P_j − Rb e_k e_kᵀ."""
import re
from fractions import Fraction as Fr
src = open("../TData.lean").read()
def mat(name):
    m = re.search(rf"^def {name} : Array \(Array Int\) := (#\[.*\])$", src, re.M)
    return [[int(v) for v in r.split(",")] for r in re.findall(r"#\[([-\d, ]+)\]", m.group(1))]
P = [mat(f"p{n}") for n in range(28)]
r2 = [int(v) for v in re.findall(r"-?\d+", re.search(r"^def r2Tab : Array Int := (#\[.*\])$", src, re.M).group(1))]
sB = [[int(v) for v in r.split(",")] for r in re.findall(r"#\[([-\d, ]+)\]", re.search(r"^def slowB : Array \(Array Int\) := (#\[.*\])$", src, re.M).group(1))]
def ldl(A):
    n = len(A); L = [[Fr(0)] * n for _ in range(n)]; D = [Fr(0)] * n
    for i in range(n):
        for j in range(i + 1):
            s = A[i][j] - sum(L[i][k] * L[j][k] * D[k] for k in range(j))
            if i == j: D[i] = s; L[i][i] = Fr(1)
            else: L[i][j] = s / D[j]
    return L, D
def q(x): return f"({x.numerator}/{x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"
out = ["import Proofs.CiProof.NodePsd", "", "/-! Generated by `Ci/proof/py/staticcert.py`: certified bounds on the slow deviations. For node interval",
       "`i`, coordinate `k` and node `j ∈ {i, i+1}`: `Rb_i · x_k² ≤ slowB[i][k]² · xᵀ P_j x`, from an exact LDLᵀ",
       "decomposition of `slowB² P_j − Rb e_k e_kᵀ` with positive pivots. -/", "", "namespace Proofs.CiProof.Skel", "open Matrix", ""]
for n in range(28):
    M = P[n]
    lhs = " + ".join(f"({M[a][b]} : ℝ) * x {a} * x {b}" for a in range(7) for b in range(7))
    out.append(f"theorem qfx{n} (x : Fin 7 → ℝ) : qf (pNode {n}) x = {lhs} := by")
    out.append(f"  unfold qf; rw [pNode{n}_eq]")
    out.append("  simp only [dotProduct, mulVec, Fin.sum_univ_seven, of_apply, cons_val', cons_val_zero, cons_val_one,")
    out.append("    empty_val', cons_val_fin_one, Matrix.cons_val, Fin.isValue]")
    out.append("  push_cast; ring")
    out.append("")
bad = 0
for i in range(27):
    Rb = max(r2[i], r2[i + 1]) + 1
    for k in range(7):
        Bk = sB[i][k]
        for j in (i, i + 1):
            A = [[Fr(Bk * Bk * P[j][a][b]) - (Fr(Rb) if a == k and b == k else 0) for b in range(7)] for a in range(7)]
            L, D = ldl(A)
            if not all(d > 0 for d in D): bad += 1; continue
            lhs = " + ".join(f"({M_} : ℝ) * x {a} * x {b}" for a in range(7) for b in range(7) for M_ in [P[j][a][b]])
            terms = " + ".join(f"{q(D[l])} * (" + " + ".join(f"{q(L[a][l])} * x {a}" for a in range(l, 7)) + ") ^ 2" for l in range(7))
            out.append(f"theorem sc_{i}_{k}_{j} (x : Fin 7 → ℝ) : ({Rb} : ℝ) * x {k} ^ 2 ≤ ({Bk} : ℝ) ^ 2 * qf (pNode {j}) x := by")
            out.append(f"  rw [qfx{j}]")
            out.append(f"  have e : ({Bk} : ℝ) ^ 2 * ({lhs}) - ({Rb} : ℝ) * x {k} ^ 2 = {terms} := by ring")
            out.append(f"  have : 0 ≤ {terms} := by positivity")
            out.append("  linarith")
            out.append("")
out.append("end Proofs.CiProof.Skel")
open("../../../proofs/Proofs/CiProof/StaticCert.lean", "w").write("\n".join(out) + "\n")
print("non-PD:", bad)
