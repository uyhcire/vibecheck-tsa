"""Generate Ci/proof/StaticCells{0..5}.lean (kernel check of staticOk per cell range) and
proofs/Proofs/CiProof/StaticDisp.lean (certificate dispatcher with table lookups)."""
import re
src = open("../TData.lean").read()
r2 = [int(v) for v in re.findall(r"-?\d+", re.search(r"^def r2Tab : Array Int := (#\[.*\])$", src, re.M).group(1))]
sB = [[int(v) for v in r.split(",")] for r in re.findall(r"#\[([-\d, ]+)\]", re.search(r"^def slowB : Array \(Array Int\) := (#\[.*\])$", src, re.M).group(1))]
N = 267; G = 6; per = (N + G - 1) // G
for g in range(G):
    lo = g * per; n = min(N, lo + per) - lo
    open(f"../StaticCells{g}.lean", "w").write(f"""import Ci.proof.StaticCheck

/-! Kernel check of `staticOk` on cells {lo}..{lo + n - 1} (generated by `Ci/proof/py/staticgen.py`). -/

namespace Ci.Proof

""" + "\n".join(f"theorem static_cell_{c} : staticOk {c} = true := by decide +kernel" for c in range(lo, lo + n)) + f"""

end Ci.Proof
""")
imps = "\n".join(f"import Ci.proof.StaticCells{g}" for g in range(G))
cases = "\n".join(f"  · exact static_cells_{g} ci (List.mem_range'_1.mpr ⟨by omega, by omega⟩)" if False else "" for g in range(G))
tree = []
def t(lo, hi, ind):
    if hi - lo == 1:
        return [f"{ind}obtain rfl : ci = {lo} := by omega", f"{ind}exact static_cell_{lo}"]
    m = (lo + hi) // 2
    out = [f"{ind}rcases Nat.lt_or_ge ci {m} with hh | hl"]
    out += [f"{ind}· " + x.lstrip() if j == 0 else f"{ind}  " + x[len(ind):] for j, x in enumerate(t(lo, m, ind))]
    out += [f"{ind}· " + x.lstrip() if j == 0 else f"{ind}  " + x[len(ind):] for j, x in enumerate(t(m, hi, ind))]
    return out
open("../StaticCells.lean", "w").write(f"""{imps}

/-! All cells pass `staticOk` (generated by `Ci/proof/py/staticgen.py`). -/

namespace Ci.Proof

theorem static_cells (ci : Nat) (hh : ci < {N}) : staticOk ci = true := by
  have hl : 0 ≤ ci := Nat.zero_le ci
""" + "\n".join(t(0, N, "  ")) + "\n\nend Ci.Proof\n")
# dispatcher
out = ["import Proofs.CiProof.StaticCert", "", "/-! Generated by `Ci/proof/py/staticgen.py`: the slow-bound certificates stated with table lookups. -/", "",
       "namespace Proofs.CiProof.Skel", "open Matrix Ci.Proof", ""]
for i in range(27):
    Rb = max(r2[i], r2[i + 1]) + 1
    for k in range(7):
        out.append(f"theorem scd_{i}_{k} (j : Nat) (hj : j = {i} ∨ j = {i + 1}) (x : Fin 7 → ℝ) :")
        out.append(f"    ((max TData.r2Tab[{i}]! TData.r2Tab[{i} + 1]! + 1 : Int) : ℝ) * x {k} ^ 2 ≤")
        out.append(f"      (((TData.slowB[{i}]!)[{k}]! : Int) : ℝ) ^ 2 * qf (pNode j) x := by")
        out.append(f"  have e1 : (max TData.r2Tab[{i}]! TData.r2Tab[{i} + 1]! + 1 : Int) = {Rb} := by decide")
        out.append(f"  have e2 : (TData.slowB[{i}]!)[{k}]! = {sB[i][k]} := by decide")
        out.append(f"  rw [e1, e2]; push_cast")
        out.append(f"  rcases hj with rfl | rfl")
        out.append(f"  · exact sc_{i}_{k}_{i} x")
        out.append(f"  · exact sc_{i}_{k}_{i + 1} x")
        out.append("")
def tk(lo, hi, ind, var, leaf):
    if hi - lo == 1: return [f"{ind}obtain rfl : {var} = {lo} := by omega"] + leaf(lo, ind)
    m = (lo + hi) // 2
    o = [f"{ind}rcases Nat.lt_or_ge {var} {m} with h{var}h | h{var}l"]
    o += [f"{ind}· " + x.lstrip() if j == 0 else f"{ind}  " + x[len(ind):] for j, x in enumerate(tk(lo, m, ind, var, leaf))]
    o += [f"{ind}· " + x.lstrip() if j == 0 else f"{ind}  " + x[len(ind):] for j, x in enumerate(tk(m, hi, ind, var, leaf))]
    return o
out.append("""theorem scd (i k j : Nat) (hi : i < 27) (hk : k < 7) (hj : j = i ∨ j = i + 1) (x : Fin 7 → ℝ) :
    ((max TData.r2Tab[i]! TData.r2Tab[i + 1]! + 1 : Int) : ℝ) * x ⟨k, hk⟩ ^ 2 ≤
      (((TData.slowB[i]!)[k]! : Int) : ℝ) ^ 2 * qf (pNode j) x := by
  have hil : 0 ≤ i := Nat.zero_le i
  have hkl : 0 ≤ k := Nat.zero_le k""")
out += tk(0, 27, "  ", "i", lambda i, ind: tk(0, 7, ind, "k", lambda k, ind2: [f"{ind2}exact scd_{i}_{k} j hj x"]))
out.append("\nend Proofs.CiProof.Skel")
open("../../../proofs/Proofs/CiProof/StaticDisp.lean", "w").write("\n".join(out) + "\n")
print("ok")
