"""Export the terminal-set certificate data (manifold table, P(h) and G(h) node tables) as Lean literals."""
import numpy as np, sys
from lin import ZI, STEP
from reduce import Y as YI, G_ as GI
from pf import NAMES
R = float(sys.argv[1]) if len(sys.argv) > 1 else 6.0
Mall = np.load("man2.npy"); hs = Mall[:,1]/65536
import os; PN = np.load(os.environ.get("PFILE", "PN.npy")); GN = np.load("GsN_fit.npy")[:,0]; HN = np.load("HN.npy")
S = np.array([STEP[i] for i in ZI], dtype=float); Sy = S[YI]; Sg = S[GI]
yidx = [ZI[i] for i in YI]; gidx = [ZI[i] for i in GI]
gidx_noac = [g for g in gidx if g != 20]
fields = yidx + gidx_noac                         # raw state indices stored in the centre table (eI = 19 is memory)
HT = np.arange(0, 2702, 2)
ctab = [[int(round(np.interp(h, hs, Mall[:,j]))) for j in fields] for h in HT]
K = 40
Pint = [[[int(round(PN[n][i][j] / (Sy[i]*Sy[j]) * 2**K)) for j in range(7)] for i in range(7)] for n in range(len(HN))]
# G raw: g_raw_dev = (Sg * G / Sy) y_raw_dev, scaled by 2^20
GK = 20
gsel = [k for k, g in enumerate(gidx) if g != 20]
Gint = [[[int(round(GN[n][k][j] * Sg[k] / Sy[j] * 2**GK)) for j in range(7)] for k in gsel] for n in range(len(HN))]
kN = np.load("kN.npy"); tkN = np.load("tkN.npy"); tpN = np.load("tpN.npy")
SAFE = float(os.environ.get("SAFE", "1.25"))   # margin on the fixed-point tolerances
kr = [[int(round(kN[n][k] / Sg[k] * 2**30)) for k in gsel] for n in range(len(HN))]
kb = [[int(round(kN[n][k] * Sg[k] * 2**20)) for k in gsel] for n in range(len(HN))]
tk = [int(round(tkN[n] * SAFE * 2**30)) for n in range(len(HN))]
tp = [[int(round(tpN[n][k] * SAFE * Sg[k])) + 2 for k in gsel] for n in range(len(HN))]
def arr(xs): return "#[" + ", ".join(str(x) for x in xs) + "]"
out = []
out.append("/-! Generated by `Ci/proof/py/export.py`: terminal-set data for `Ci.Proof.inT`. Do not edit by hand. -/\n")
out.append("set_option maxRecDepth 100000\n\nnamespace Ci.Proof.TData\n")
out.append(f"/-- State fields (raw indices into the 19-field state, 19 = law memory `eI`) of the centre table. -/\ndef fields : Array Nat := {arr(fields)}\n")
out.append(f"/-- Slow coordinates are the first 7 fields; the rest are fast (slaved) coordinates. -/\ndef nSlow : Nat := 7\n")
for n, r in enumerate(ctab): out.append(f"def c{n} : Array Int := {arr(r)}")
out.append("/-- Climb manifold: centre values (raw) at h = 0, 2, ..., 2700 m. -/\ndef centre : Array (Array Int) := #[" + ", ".join(f"c{n}" for n in range(len(ctab))) + "]\n")
out.append(f"/-- Quadratic form at h = 0, 100, ..., 2700 m, raw slow deviations, scaled by 2^{K}. -/\ndef pK : Nat := {K}\n")
for n, P in enumerate(Pint): out.append(f"def p{n} : Array (Array Int) := #[" + ", ".join(arr(r) for r in P) + "]")
out.append("def pTab : Array (Array (Array Int)) := #[" + ", ".join(f"p{n}" for n in range(len(Pint))) + "]\n")
out.append(f"/-- Fast-coordinate slaving gains at the same nodes, raw per raw, scaled by 2^{GK}. -/\ndef gK : Nat := {GK}\n")
for n, G in enumerate(Gint): out.append(f"def g{n} : Array (Array Int) := #[" + ", ".join(arr(r) for r in G) + "]")
out.append("def gTab : Array (Array (Array Int)) := #[" + ", ".join(f"g{n}" for n in range(len(Gint))) + "]\n")
out.append("/-- Kink direction of the fast residual (per raw unit, scaled 2^30) at the same nodes. -/\ndef kTab : Array (Array Int) := #[" + ", ".join(arr(t) for t in kr) + "]\n")
out.append("/-- The same direction in raw units per unit of the kink coordinate, scaled 2^20. -/\ndef kbTab : Array (Array Int) := #[" + ", ".join(arr(t) for t in kb) + "]\n")
out.append("/-- Bound on the kink coordinate (scaled 2^30). -/\ndef tkTab : Array Int := " + arr(tk) + "\n")
out.append("/-- Bounds (raw) on the fast residual after removing the kink component. -/\ndef tpTab : Array (Array Int) := #[" + ", ".join(arr(t) for t in tp) + "]\n")
import boxes3
cellsBox = []
for a in np.arange(10, 2680, 10):
    lo, hi, d = boxes3.cellbox(a, min(a + 10, 2680))
    cellsBox.append([int(v) for v in list(lo) + list(hi)] + [d[4], d[5]])
for n, b in enumerate(cellsBox): out.append(f"def b{n} : Array Int := {arr(b)}")
out.append("/-- Bounding box of the set in each 10 m altitude cell from 10 m: 19 lows, 19 highs (x unused), then the\nintegrator memory eI's low and high. Redundant with the conditions above by construction (padded); it lets the\none-tick safety proof work on boxes. -/\ndef boxTab : Array (Array Int) := #[" + ", ".join(f"b{n}" for n in range(len(cellsBox))) + "]\n")
import kinv
out.append(f"/-- Radius² of the slow ellipsoid at the form's nodes, scaled by 2^{K}: {kinv.R} up to 2200 m, {kinv.RTOP} from 2400 m. -/\ndef r2Tab : Array Int := " + arr([int(round(v * 2**K)) for v in kinv.r2N]) + "\n")
out.append("end Ci.Proof.TData\n")
open("../TData.lean", "w").write("\n".join(out))
print("fields", [NAMES[i] if i < 21 else i for i in fields], "tk", tk[:3], "tp", tp[3])
